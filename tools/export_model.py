# -*- coding: utf-8 -*-
"""Export checkpoints/dqn_snake_best.pt to play/model/snake_cnn_fp16.js (float16, base64).

    python -m tools.export_model

The page loads it with a plain <script> tag (works under file://, no fetch).
"""

import base64
import json

import numpy as np

from tools.common import CKPT, MODEL_JS, RESULT_JSON, ROOT, TENSOR_ORDER, load_checkpoint


def export_blob(sd):
    """state_dict -> (tensor table, raw little-endian float16 bytes)."""
    table, chunks, off = [], [], 0
    for name in TENSOR_ORDER:
        a = sd[name].detach().cpu().numpy().astype("<f2")
        table.append({"name": name, "shape": list(a.shape), "offset": off, "length": int(a.size)})
        chunks.append(a.tobytes())
        off += int(a.size)
    assert set(sd.keys()) == set(TENSOR_ORDER), "unexpected tensors in checkpoint"
    return table, b"".join(chunks)


def decode_js(path=MODEL_JS):
    """Read the exported .js back into {name: float32 ndarray} (used by tests)."""
    text = path.read_text(encoding="utf-8")
    payload = json.loads(text[text.index("{"): text.rindex("}") + 1])
    raw = np.frombuffer(base64.b64decode(payload["b64"]), dtype="<f2")
    out = {}
    for t in payload["tensors"]:
        out[t["name"]] = raw[t["offset"]: t["offset"] + t["length"]].astype(np.float32).reshape(t["shape"])
    return payload, out


def main():
    ck = load_checkpoint()
    table, raw = export_blob(ck["model"])
    params = sum(t["length"] for t in table)
    ev = None
    if RESULT_JSON.exists():
        r = json.loads(RESULT_JSON.read_text(encoding="utf-8"))
        e30 = r["eval"]["float32"]["eval30_seed999"]
        e30h = r["eval"]["float16"]["eval30_seed999"]
        ev = {"games": e30["games"], "seed": e30["seed"], "avg_score": e30["avg_score"],
              "avg_steps": e30["avg_steps"], "avg_score_fp16": e30h["avg_score"],
              "avg_steps_fp16": e30h["avg_steps"], "source": "results/result.json"}
    meta = {
        "source": CKPT.name, "n": int(ck["n"]), "channels": int(ck["channels"]),
        "params": int(params), "dtype": "float16",
        "layers": [
            {"key": "conv1", "kind": "conv", "in": 5, "out": 32, "k": 3},
            {"key": "conv2", "kind": "conv", "in": 32, "out": 64, "k": 3},
            {"key": "conv3", "kind": "conv", "in": 64, "out": 64, "k": 3},
            {"key": "fc1", "kind": "fc", "in": 64 * int(ck["n"]) ** 2, "out": 256},
            {"key": "fc2", "kind": "fc", "in": 256, "out": 4},
        ],
        "eval": ev,
    }
    # sanity: layer table agrees with tensor shapes
    shp = {t["name"]: t["shape"] for t in table}
    for L in meta["layers"]:
        w = shp[L["key"] + ".weight"]
        assert w[0] == L["out"] and w[1] == L["in"], (L, w)
    payload = {"format": "fp16-b64-v1", "meta": meta, "tensors": table,
               "b64": base64.b64encode(raw).decode("ascii")}
    MODEL_JS.parent.mkdir(parents=True, exist_ok=True)
    MODEL_JS.write_text("/* Generated by tools/export_model.py from checkpoints/" + CKPT.name +
                        " -- do not edit. */\nwindow.SNAKE_MODEL = " +
                        json.dumps(payload, separators=(",", ":")) + ";\n", encoding="utf-8")
    print(f"wrote {MODEL_JS.relative_to(ROOT)}: {params} params, {MODEL_JS.stat().st_size} bytes")


if __name__ == "__main__":
    main()
