# -*- coding: utf-8 -*-
"""Re-evaluate the shipped checkpoint and write results/result.json.

    python -m tools.eval_model

Greedy policy (epsilon = 0, 180-degree turns masked), fixed seeds, so the numbers are
reproducible. Protocol "eval30" is exactly train.py's final evaluation
(`evaluate(net, n, 30)`, seed 999); "eval20" is train.py's periodic evaluation.
Both float32 weights and float16-rounded weights (what the browser uses) are evaluated.
"""

import json
import time

import numpy as np

from tools.common import CKPT, RESULT_JSON, ROOT, build_net, load_checkpoint


def rollout_games(net, n, games, seed):
    """Same loop as train.evaluate, but keeps per-game score / steps / end reason."""
    import torch
    from snake_env import SnakeEnv
    env = SnakeEnv(n, seed)
    out = []
    with torch.no_grad():
        for _ in range(games):
            s = env.reset()
            info = {}
            while not env.done:
                q = net(torch.from_numpy(s).unsqueeze(0))[0]
                q = q + torch.tensor(env.legal_mask()).log()
                s, _, _, info = env.step(int(q.argmax()))
            out.append({"score": env.score, "steps": env.steps, "reason": info.get("reason", "")})
    return out


def summarize(games):
    sc = [g["score"] for g in games]
    st = [g["steps"] for g in games]
    reasons = {}
    for g in games:
        reasons[g["reason"]] = reasons.get(g["reason"], 0) + 1
    return {"games": len(games), "avg_score": float(np.mean(sc)),
            "avg_steps": float(np.mean(st)), "max_score": int(max(sc)),
            "min_score": int(min(sc)), "end_reasons": reasons,
            "scores": sc, "steps": st}


def main():
    from train import evaluate
    ck = load_checkpoint()
    n = int(ck["n"])
    nets = {"float32": build_net(ck), "float16": build_net(ck, fp16=True)}
    params = sum(p.numel() for p in nets["float32"].parameters())
    layers = {k: int(v.numel()) for k, v in ck["model"].items()}
    res = {
        "_note": "Generated by `python -m tools.eval_model`. Greedy policy, fixed seeds; "
                 "training steps and wall-clock time of the shipped checkpoint were not recorded.",
        "checkpoint": {"file": "checkpoints/" + CKPT.name, "bytes": CKPT.stat().st_size,
                       "grid": n, "channels": int(ck["channels"]),
                       "avg_score_stored_in_checkpoint": ck.get("avg_score"),
                       "params": int(params), "tensor_sizes": layers},
        "training": {"steps": None, "episodes": None, "wall_clock_minutes": None,
                     "recorded": False,
                     "retrain_command": "python train.py --grid 10 --max-minutes 15"},
        "eval": {},
    }
    t0 = time.time()
    for prec, net in nets.items():
        for name, games, seed in (("eval30_seed999", 30, 999), ("eval20_seed999", 20, 999)):
            g = rollout_games(net, n, games, seed)
            s = summarize(g)
            s["seed"] = seed
            # cross-check against train.evaluate (same protocol)
            ref_score, ref_len = evaluate(net, n, games, seed)
            assert abs(ref_score - s["avg_score"]) < 1e-6 and abs(ref_len - s["avg_steps"]) < 1e-6
            res["eval"].setdefault(prec, {})[name] = s
    res["eval_seconds"] = round(time.time() - t0, 1)
    RESULT_JSON.parent.mkdir(exist_ok=True)
    RESULT_JSON.write_text(json.dumps(res, ensure_ascii=False, indent=2), encoding="utf-8")
    e = res["eval"]
    print(f"wrote {RESULT_JSON.relative_to(ROOT)}: params={params} "
          f"fp32 eval30={e['float32']['eval30_seed999']['avg_score']} "
          f"fp16 eval30={e['float16']['eval30_seed999']['avg_score']}")


if __name__ == "__main__":
    main()
