# -*- coding: utf-8 -*-
"""Evaluate every brain of play/js/config.js with the NumPy reference (brains.py) and write
results/brains.json + play/js/results.js (the numbers the page and README show).

    python -m tools.eval_brains              # all brains, 30 games, seed 999 (a few minutes, CPU only)
    python -m tools.eval_brains --games 10   # quicker smoke run (do not commit)
    python -m tools.eval_brains --js         # also run the same games in the browser code (Node) and require identical results

Protocol: snake_env.SnakeEnv, fixed seed, each brain with its DEFAULT policy (greedy / sample) and
guard setting from config.js, plus the documented variants (brain B without guard, the MLP greedy).
The page's watch mode replays the same games (seed 999), so the first 30 games you see are these.
"""

import argparse
import json
import random
import re
import shutil
import subprocess
import sys
import tempfile
import time
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parent.parent
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from brains import MASKS, load_brain, summarize  # noqa: E402
from snake_env import SnakeEnv  # noqa: E402

OUT_JSON = ROOT / "results" / "brains.json"
OUT_JS = ROOT / "play" / "js" / "results.js"
SEED = 999


def config_brains():
    """[{id, file, policy, guard}] from play/js/config.js (plain regex; the file is simple JS)."""
    cfg = (ROOT / "play" / "js" / "config.js").read_text(encoding="utf-8")
    out = []
    for m in re.finditer(r'\{\s*id:\s*"([a-z0-9_]+)",\s*file:\s*"([^"]+)"(.*?)blurb:', cfg, re.S):
        body = m.group(3)
        pol = re.search(r'policy:\s*"(greedy|sample)"', body).group(1)
        guard = re.search(r"guard:\s*(true|false)", body).group(1) == "true"
        out.append({"id": m.group(1), "file": m.group(2), "policy": pol, "guard": guard})
    return out


def play(brain, games, seed, policy, guard, max_steps=5000):
    """guard: "trained" = the model's own mask; "safe" / "turn" / "none" override it."""
    env = SnakeEnv(brain.n, seed)
    rng = random.Random(seed)
    mask_fn = MASKS[brain.spec["mask"] if guard == "trained" else guard]
    out = []
    for _ in range(games):
        env.reset()
        info = {}
        while not env.done and env.steps < max_steps:
            bm = brain.env_mask_to_brain(mask_fn(env))
            r = brain.forward(brain.obs(env), bm)
            if policy == "sample":
                m = np.array(bm) > 0
                lg = np.where(m, r["logits"], -np.inf)
                p = np.exp(lg - lg[m].max())
                p /= p.sum()
                u, c, a = rng.random(), 0.0, 3
                for i in range(4):
                    if p[i] <= 0:
                        continue
                    c += p[i]
                    a = i
                    if u < c:
                        break
            else:
                a = r["action"]
            _, _, _, info = env.step(brain.action_map[a])
        out.append({"score": env.score, "steps": env.steps, "length": len(env.snake),
                    "reason": info.get("reason", "达到步数上限")})
    return out


def js_play(model_rel, games, seed, policy, guard):
    node = shutil.which("node") or r"C:\Program Files\nodejs\node.exe"
    if not Path(node).exists():
        raise SystemExit("Node.js not found (needed for --js)")
    f = Path(tempfile.gettempdir()) / ("eval_brains_%d.json" % (time.time() * 1000))
    f.write_text(json.dumps({"cmd": "rollout", "model": model_rel, "games": games, "seed": seed, "policy": policy, "guard": guard}), encoding="utf-8")
    p = subprocess.run([node, str(ROOT / "tests" / "js" / "harness.js"), str(f)], capture_output=True, timeout=7200)
    f.unlink(missing_ok=True)
    if p.returncode:
        raise SystemExit(p.stderr.decode("utf-8", "replace"))
    return json.loads(p.stdout.decode("utf-8"))


def variants_for(b):
    """(label, policy, guard) rows to evaluate for a brain: default first, then documented alternatives."""
    rows = [("default", b["policy"], "safe" if b["guard"] else "trained")]
    if b["id"] == "ppo_ray":
        rows.append(("no_guard", "greedy", "trained"))
        rows.append(("sample_no_guard", "sample", "trained"))
    if b["id"] == "ppo_mlp_linyi":
        rows.append(("greedy", "greedy", "trained"))
    if b["id"] == "ppo_linyi":
        rows.append(("sample", "sample", "trained"))
    return rows


def write_results_js(data):
    keep = {}
    for bid, d in data["brains"].items():
        keep[bid] = {k: {kk: vv for kk, vv in v.items() if kk not in ("scores", "steps")} for k, v in d["eval"].items()}
    OUT_JS.write_text("/* Generated by tools/eval_brains.py from results/brains.json -- rebuild, do not edit. */\n"
                      "window.BRAIN_RESULTS = " + json.dumps(keep, ensure_ascii=False) + ";\n", encoding="utf-8")


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--games", type=int, default=30)
    ap.add_argument("--seed", type=int, default=SEED)
    ap.add_argument("--js", action="store_true", help="also run the browser code in Node and require identical games")
    ap.add_argument("--only", help="brain id")
    args = ap.parse_args(argv)
    data = {"_note": "Generated by `python -m tools.eval_brains`: NumPy reference (brains.py) on snake_env.SnakeEnv, fixed seed. "
                     "Each brain with its default policy / guard from play/js/config.js plus documented variants. "
                     "Sampling uses random.Random(seed) exactly like play/js (PyRandom), so the browser replays the same games.",
            "seed": args.seed, "games": args.games, "brains": {}}
    if OUT_JSON.exists() and args.only:
        data = json.loads(OUT_JSON.read_text(encoding="utf-8"))
    t0 = time.time()
    for b in config_brains():
        if args.only and b["id"] != args.only:
            continue
        brain = load_brain(ROOT / "play" / b["file"])
        entry = {"file": b["file"], "n": brain.n, "params": brain.params, "obs": brain.spec["obs"], "trained_mask": brain.spec["mask"],
                 "source": brain.meta.get("source"), "default": {"policy": b["policy"], "guard": b["guard"]}, "eval": {}}
        for label, policy, guard in variants_for(b):
            t1 = time.time()
            games = play(brain, args.games, args.seed, policy, guard)
            s = summarize(games)
            s.update({"policy": policy, "guard": guard, "seed": args.seed, "seconds": round(time.time() - t1, 1)})
            if args.js:
                jg = js_play(b["file"], args.games, args.seed, policy, guard)
                same = [(g["score"], g["steps"]) for g in jg] == [(g["score"], g["steps"]) for g in games]
                s["js_identical"] = same
                if not same:
                    raise SystemExit("browser code and NumPy reference disagree for %s/%s" % (b["id"], label))
            entry["eval"][label] = s
            print("%-14s %-16s policy=%-6s guard=%-7s avg=%.2f max=%d min=%d steps=%.0f  (%.0fs)" % (
                b["id"], label, policy, guard, s["avg_score"], s["max_score"], s["min_score"], s["avg_steps"], s["seconds"]), flush=True)
        data["brains"][b["id"]] = entry
    data["seconds"] = round(time.time() - t0, 1)
    OUT_JSON.parent.mkdir(exist_ok=True)
    OUT_JSON.write_text(json.dumps(data, ensure_ascii=False, indent=2), encoding="utf-8")
    write_results_js(data)
    print("wrote", OUT_JSON.relative_to(ROOT), "and", OUT_JS.relative_to(ROOT))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
