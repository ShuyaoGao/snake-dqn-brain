# -*- coding: utf-8 -*-
"""One command to build the static page (play/) and the release zip.

    python -m tools.build              # credits.js (+ model .js if PyTorch is installed)
    python -m tools.build --eval       # also re-run the evaluation -> results/result.json
    python -m tools.build --release    # also write release/<repo>-v<version>.zip (play/ only)

play/ is plain HTML + JS: it runs from file:// (double-click index.html) without Python.
"""

import argparse
import json
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PLAY = ROOT / "play"
RELEASE = ROOT / "release"
ZIP_LIMIT = 15 * 1024 * 1024


def load_credits():
    for p in (ROOT / "credits.json", ROOT / "tools" / "credits.default.json"):
        if p.exists():
            return json.loads(p.read_text(encoding="utf-8"))
    raise FileNotFoundError("credits.json not found")


def write_credits_js(credits):
    keep = {k: v for k, v in credits.items() if not k.startswith("_")}
    js = ("/* Generated by tools/build.py from credits.json -- edit credits.json, then rebuild. */\n"
          "window.CREDITS = " + json.dumps(keep, ensure_ascii=False, indent=2) + ";\n")
    out = PLAY / "js" / "credits.js"
    out.write_text(js, encoding="utf-8")
    return out


def make_zip(credits):
    RELEASE.mkdir(exist_ok=True)
    name = f"{credits.get('REPO_NAME', 'snake-dqn-brain')}-v{credits.get('VERSION', '1.0')}.zip"
    out = RELEASE / name
    files = sorted(p for p in PLAY.rglob("*") if p.is_file())
    # the zip also carries the root index.html (meta refresh -> play/index.html), so that
    # "unzip, then double-click index.html" works exactly like the repository root
    root_index = ROOT / "index.html"
    if not root_index.exists():
        root_index = ROOT / "tools" / "publish_templates" / "index.html.tmpl"
    entries = [("play/" + p.relative_to(PLAY).as_posix(), p) for p in files]
    if root_index.exists():
        entries.append(("index.html", root_index))
    with zipfile.ZipFile(out, "w", zipfile.ZIP_DEFLATED, compresslevel=9) as z:
        for name, p in entries:
            info = zipfile.ZipInfo(name, date_time=(2026, 1, 1, 0, 0, 0))
            info.compress_type = zipfile.ZIP_DEFLATED
            info.external_attr = 0o644 << 16
            z.writestr(info, p.read_bytes())
    size = out.stat().st_size
    if size > ZIP_LIMIT:
        raise SystemExit(f"release zip is {size} bytes > 15 MB limit")
    return out, size, len(entries)


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--eval", action="store_true", help="re-run tools.eval_model first (needs PyTorch)")
    ap.add_argument("--release", action="store_true", help="also build the release zip")
    ap.add_argument("--skip-model", action="store_true", help="do not re-export the model .js")
    args = ap.parse_args(argv)

    credits = load_credits()
    if args.eval:
        from tools import eval_model
        eval_model.main()
    if not args.skip_model:
        try:
            import torch  # noqa: F401
        except ImportError:
            print("PyTorch not installed: keeping the existing play/model/snake_cnn_fp16.js")
        else:
            from tools import export_model
            export_model.main()
    print("wrote", write_credits_js(credits).relative_to(ROOT))
    total = sum(p.stat().st_size for p in PLAY.rglob("*") if p.is_file())
    print(f"play/ = {total} bytes")
    if args.release:
        out, size, n = make_zip(credits)
        print(f"wrote {out.relative_to(ROOT)}: {n} files, {size} bytes")


if __name__ == "__main__":
    main()
